export function buildHoneypotPool() {
  const pool: {
    seq: number;
    event: CanonicalPaymentEvent;
    goldPayload: GoldRisk;
  }[] = [];
  let idx = 0;
  for (const batch of SAMPLE_BATCHES) {
    for (const u of batch.units) {
      if (!u.event.gold) continue;
      idx++;
      const { gold: g, ...event } = u.event;
      pool.push({ seq: idx, event, goldPayload: g });
    }
  }
  return pool;
}

